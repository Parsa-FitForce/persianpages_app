export function buildBrowsePageContent({
  countryName,
  cityName,
  categorySlug,
  categoryName,
  totalCount,
}: BrowseContentInput): BrowsePageContent {
  const location = cityName ? `${cityName}، ${countryName}` : countryName;
  const subject = categoryName ? `${categoryName} ایرانی` : 'کسب‌وکار ایرانی';
  const subjectPlural = categoryName ? `${categoryName} ایرانی` : 'کسب‌وکارهای ایرانی';
  const count = totalCount.toLocaleString('fa-IR');
  const guidance = categorySlug ? CATEGORY_GUIDANCE[categorySlug] || DEFAULT_GUIDANCE : DEFAULT_GUIDANCE;

  return {
    intro: `در این صفحه ${count} ${subject} در ${location} را می‌بینید. هر نتیجه به یک صفحه اختصاصی با توضیحات، نشانی، راه تماس و وب‌سایت کسب‌وکار پیوند دارد.`,
    overviewHeading: `راهنمای پیدا کردن ${subjectPlural} در ${location}`,
    paragraphs: [
      guidance.coverage,
      `پرشین‌پیجز نتیجه‌های این صفحه را بر اساس موقعیت و دسته‌بندی مرتب می‌کند. از فیلترهای شهر و دسته‌بندی برای محدود کردن فهرست استفاده کنید و سپس اطلاعات صفحه هر کسب‌وکار را با منبع رسمی آن مقایسه کنید.`,
    ],
    checklistHeading: 'پیش از انتخاب چه چیزهایی را بررسی کنیم؟',
    checklist: guidance.checklist,
    accuracyNote: 'اطلاعات تماس، ساعات کاری، قیمت‌ها و شرایط خدمات ممکن است تغییر کند. پیش از مراجعه یا پرداخت، جزئیات را مستقیماً با کسب‌وکار تأیید کنید.',
    metaDescription: `فهرست ${count} ${subject} در ${location} همراه با توضیحات، نشانی، شماره تماس و وب‌سایت در پرشین‌پیجز.`,
  };
}

